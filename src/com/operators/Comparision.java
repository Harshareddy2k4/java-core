package com.operators;

public class Comparision {

	public static void main(String[] args) {
		System.out.println("Welcome to comparision Operators");
		int a = 45;
		int b = 69;
		int c = 45;
		System.out.println(a==b);
		System.out.println(a<b);
		System.out.println(a>b);
		System.out.println(a>=c);
		System.out.println(a<=c);
		System.out.println(a!=b);

	}

}

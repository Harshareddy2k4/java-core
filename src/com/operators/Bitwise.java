package com.operators;

public class Bitwise {

	public static void main(String[] args) {
		System.out.println("Welcome to Bitwise Operator");
		System.out.println(20&10);
		System.out.println(69&45);
		System.out.println(20|10);
		System.out.println(69|45);
		System.out.println(69^45);
		System.out.println(~68);
		
	}

}

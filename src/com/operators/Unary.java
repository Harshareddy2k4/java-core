package com.operators;

public class Unary {

	public static void main(String[] args) {
		System.out.println("Welcome to Unary Operators");
		int a =5;
		int b = 6;
		System.out.println(++a);
		System.out.println(++b);
		System.out.println(a--);
		System.out.println(++a);
		System.out.println(--b);
		System.out.println(b--);
		System.out.println(a+b);
		System.out.println(a);
		System.out.println(b);

	}

}
